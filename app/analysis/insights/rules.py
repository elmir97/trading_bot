"""Пороги детекторов закономерностей.

Вынесены отдельно, чтобы менять чувствительность анализа без правки логики.
Все значения консервативные: лучше не показать слабую закономерность,
чем выдать шум за вывод.
"""

from __future__ import annotations

from decimal import Decimal

# --- Размеры выборок -------------------------------------------------------

# Минимум сделок в группе, чтобы группа вообще попала в отчёт.
MIN_GROUP_SAMPLE = 8

# Минимум сделок за период, чтобы запускать AI-анализ.
MIN_PERIOD_SAMPLE = 20

# Границы уверенности по размеру выборки.
CONFIDENCE_MEDIUM_SAMPLE = 15
CONFIDENCE_HIGH_SAMPLE = 30

# --- Пороги эффекта --------------------------------------------------------

# На сколько R expectancy группы должна отличаться от общей,
# чтобы считать отличие содержательным.
MIN_EXPECTANCY_GAP_R = Decimal("0.25")

# Доля запланированного RR, ниже которой фиксация прибыли считается ранней.
EARLY_EXIT_RATIO = Decimal("0.5")

# --- Поведенческие детекторы ----------------------------------------------

# Вход в течение стольких минут после закрытия убытка — кандидат в revenge trade.
REVENGE_WINDOW_MINUTES = 60

# Сделок за календарный день, начиная с которого день считается перегруженным.
OVERTRADING_DAILY_TRADES = 5

# Длина серии убытков, после которой отслеживается поведение.
LOSS_STREAK_LENGTH = 2

# --- Бакеты удержания позиции (часы) ---------------------------------------

DURATION_BUCKETS: tuple[tuple[str, Decimal, Decimal | None], ...] = (
    ("<1ч", Decimal("0"), Decimal("1")),
    ("1-4ч", Decimal("1"), Decimal("4")),
    ("4-12ч", Decimal("4"), Decimal("12")),
    ("12-24ч", Decimal("12"), Decimal("24")),
    (">24ч", Decimal("24"), None),
)

# --- Часовые бакеты (UTC) --------------------------------------------------

HOUR_BUCKETS: tuple[tuple[str, int, int], ...] = (
    ("00-06", 0, 6),
    ("06-12", 6, 12),
    ("12-18", 12, 18),
    ("18-24", 18, 24),
)

WEEKDAY_NAMES: tuple[str, ...] = ("Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс")


def confidence_for(sample_size: int) -> str:
    """Ординальная оценка доверия к выводу по размеру выборки.

    Это не статистическая значимость — намеренно. Отдельная сделка может
    перекосить любую группу, поэтому шкала грубая и честная.
    """
    if sample_size >= CONFIDENCE_HIGH_SAMPLE:
        return "high"
    if sample_size >= CONFIDENCE_MEDIUM_SAMPLE:
        return "medium"
    return "low"
