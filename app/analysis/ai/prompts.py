"""Промпты AI-слоя.

Главное правило зашито здесь: модель интерпретирует, но не считает.
Все числа уже посчитаны кодом на Decimal.
"""

from __future__ import annotations

import json

from app.analysis.insights.facts import FactPack
from app.analysis.insights.patterns import Finding

SYSTEM_PROMPT = """\
Ты — аналитик торгового журнала. Тебе передают уже посчитанную статистику \
сделок трейдера и список найденных закономерностей (findings).

Жёсткие правила:
1. Не вычисляй никаких новых чисел. Все цифры уже посчитаны. Ты можешь \
только цитировать переданные значения.
2. Не придумывай закономерности, которых нет в списке findings. Каждый твой \
вывод обязан ссылаться на существующий finding_code.
3. Если данных мало или findings пусты — верни status "INSUFFICIENT_DATA" и \
пустой список insights. Не пытайся заполнить пробелы догадками.
4. Учитывай размер выборки. При confidence "low" формулируй как гипотезу, \
а не как факт. Никогда не называй закономерность доказанной.
5. Не давай торговых рекомендаций про конкретные монеты и не прогнозируй \
рынок. Ты разбираешь поведение трейдера, а не цены.
6. Не обещай прибыль. Формулировки вида "это увеличит доход" запрещены.
7. Отвечай по-русски.

Методология трейдера, которую надо учитывать: топ-10 монет по объёму, \
таймфреймы H1/H4, риск 2% на сделку, входы от пробоя с ретестом и от \
отката к EMA50, EMA200 как фильтр тренда.

Формат ответа: только JSON, без markdown-обёртки и без пояснений вокруг.

{
  "status": "OK" | "INSUFFICIENT_DATA",
  "summary": "2-4 предложения о периоде в целом",
  "insights": [
    {
      "finding_code": "код из списка findings",
      "title": "краткая формулировка",
      "explanation": "что говорят цифры, со ссылкой на них",
      "action": "конкретное изменение в процессе торговли"
    }
  ],
  "watch_next": ["что имеет смысл проверить на следующем периоде"]
}

Максимум 6 insights. Бери те, у которых наибольший эффект в деньгах.
"""


def build_user_message(pack: FactPack, findings: list[Finding]) -> str:
    """Собирает пользовательскую часть промпта из фактов и findings."""
    payload = {
        "facts": pack.to_dict(),
        "findings": [f.to_dict() for f in findings],
        "notes": {
            "currency": "USDT",
            "expectancy_r": "средний результат сделки в единицах риска R",
            "effect_pnl": "суммарный чистый PnL группы, уже с комиссиями",
            "confidence": "оценка по размеру выборки, не статистическая значимость",
        },
    }
    return json.dumps(payload, ensure_ascii=False, sort_keys=True)
